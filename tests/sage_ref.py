"""Runs Sage's own step code (sage_rl/src/sage.cc at SAGE_COMMIT) on recorded
TCP_INFO readings, for comparison with guest/src/step.rs.

The harness is assembled from line ranges of the unmodified sage.cc: its
defines and globals, the declarations at the top of CntThread, and the body
that turns one TCP_INFO reading into the state message. Only the clock (the
recorded step time) and the TCP_INFO read (the recorded bytes) are stubbed,
and the message is printed instead of written to shared memory.
"""

from __future__ import annotations

import shutil
import struct
import subprocess
from pathlib import Path
from typing import Final

SAGE_COMMIT: Final = "eedd28110278f7b9cac4fb05f2570dd7d43b0529"
# (first, last) lines of sage.cc at SAGE_COMMIT, inclusive.
_PREAMBLE: Final = (28, 98)  # defines, #include "define.h", globals
_LOCALS: Final = [(496, 506), (550, 652)]  # CntThread's declarations
_STEP: Final = (675, 1016)  # one TCP_INFO reading -> message
INFO_LEN: Final = 224


def _lines(src: list[str], first: int, last: int) -> str:
    return "".join(src[first - 1 : last])


def build(sage_dir: Path, out: Path) -> Path:
    src_dir = sage_dir / "sage_rl" / "src"
    src = (src_dir / "sage.cc").read_text().splitlines(keepends=True)
    harness = "\n".join(
        [
            "// Generated by tests/sage_ref.py from Sage's sage.cc; see there.",
            "#define timestamp sage_timestamp_unused",
            "#define raw_timestamp sage_raw_timestamp_unused",
            _lines(src, *_PREAMBLE),
            "#undef timestamp",
            "#undef raw_timestamp",
            "static uint64_t harness_now_us;",
            "static uint64_t timestamp(void) { return harness_now_us; }",
            "static uint64_t raw_timestamp(void) { return harness_now_us; }",
            "int main(int argc, char **argv) {",
            "  if (argc != 3) return 2;",
            "  harness_now_us = strtoull(argv[1], NULL, 10);",
            "  start_timestamp = strtoull(argv[2], NULL, 10);",
            "  send_begun = harness_now_us;",
            "  report_period = 10;",
            "  static char shm[4096], shm_rl[16];",
            "  shared_memory = shm; shared_memory_rl = shm_rl;",
            "  int msg_id = 657;",
            *(_lines(src, a, b) for a, b in _LOCALS),
            "  uint64_t t;",
            "  while (fread(&t, 8, 1, stdin) == 1",
            f"         && fread(&sage_info, {INFO_LEN}, 1, stdin) == 1) {{",
            "    harness_now_us = t;",
            "    got_no_zero = 0;",
            _lines(src, *_STEP),
            '    if (got_no_zero) printf("%s\\n", message);',
            "  }",
            "  return 0;",
            "}",
            "",
        ]
    )
    (out / "harness.cc").write_text(harness)
    exe = out / "sage_harness"
    subprocess.run(
        [
            "g++",
            "-O1",
            "-w",
            "-I",
            str(src_dir),
            "-o",
            str(exe),
            str(out / "harness.cc"),
            "-lpthread",
        ],
        check=True,
    )
    return exe


def run(
    exe: Path, readings: list[tuple[int, bytes]], start_us: int, base_ms: int
) -> list[list[str]]:
    """Sage's message for each (time us, TCP_INFO bytes) reading that moved
    the ACK state, split into its 77 fields."""
    stdin = b"".join(struct.pack("<Q", t) + info[:INFO_LEN] for t, info in readings)
    out = subprocess.run(
        [str(exe), str(start_us), str(base_ms)], input=stdin, capture_output=True, check=True
    ).stdout.decode()
    return [line.split() for line in out.splitlines()]


def available() -> bool:
    return shutil.which("g++") is not None
